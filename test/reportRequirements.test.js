const assert = require('assert/strict');
const mongoose = require('mongoose');
const ExcelJS = require('exceljs');
const { extractExtendedFields: fields } = require('../src/services/unitFields');
const { buildProjectInventory, movementRows, summarize } = require('../src/services/inventoryReport');
const { trackedBulkWrite, markMissing } = require('../src/services/inventoryHistory');
const { buildExcelReport } = require('../src/services/excelService');
const { getWeeklyPeriod } = require('../src/services/weeklyReportService');
async function main() {
  const {reportPrices}=require('../src/services/reportPrices');
  const unverified=reportPrices({source:'salepro',price:1,raw_data:{price_per_meter:0.006}});
  assert.equal(unverified.price,'-');assert.equal(unverified.unitPrice,'-');assert.ok(unverified.qualityNote);
  assert.equal(reportPrices({source:'hisale',price:8172327510,raw_data:{priceAveFull:'71.1 triệu/m'}}).price,8172327510);
  const high = { source:'vhub',area_land:70,raw_data:{productType:'cao_tang',frontWidth:null} };
  assert.equal(fields(high).frontWidth,'');
  assert.equal(fields({...high,raw_data:{productType:'thap_tang',frontWidth:'5,5'}}).frontWidth,5.5);
  assert.equal(fields({...high,raw_data:{productType:'thap_tang',frontWidth:'Đang cập nhật'}}).frontWidth,'-');
  assert.equal(fields({source:'vhub',raw_data:{}}).priceLoan,'');
  assert.equal(fields({source:'vhub',raw_data:{loanPrice:0}}).priceLoan,'-');
  assert.equal(fields({source:'salepro',raw_data:{project_type:'low_rise'}}).priceTttd,'');
  assert.equal(fields({source:'salepro',raw_data:{project_type:'high_rise'}}).priceTttd,'-');
  assert.equal(fields({source:'salepro',raw_data:{project_type:'high_rise',progress_payment_price:123}}).priceTttd,123);
  assert.equal(fields({source:'hisale',price:1e9,area_land:50,raw_data:{priceAveFull:'0.0 triệu/m',priceAve:'71,1 triệu/m'}}).unitPrice,71100000);
  assert.equal(fields({source:'hisale',price:1e9,area_land:50,raw_data:{}}).unitPrice,'-');
  assert.equal(fields({source:'hisale',raw_data:{fund_type:0,fundTypeName:'Loại quỹ'}}).hisaleQuyCan,'-');
  assert.equal(fields({source:'hisale',raw_data:{fund_type:2}}).hisaleQuyHot,'Yes');
  assert.equal(fields({source:'salepro',raw_data:{apartment_axis_code:'01.06'}}).axis,'01.06');
  assert.equal(fields({source:'salepro',raw_data:{price_per_meter:0.003}}).unitPrice,0.003);
  const { normalizeHighRiseUnit } = require('../src/crawlers/saleproHighRiseCrawler');
  const { normalizeVhubUnit } = require('../src/crawlers/vhubCrawler');
  assert.equal(normalizeHighRiseUnit({product_code:'SOLD',project_name:'TEST',state_line:'sold',state:'sold'}).status,'Đã bán');
  assert.equal(normalizeVhubUnit({productCode:'SOLD',projectName:'TEST',projectId:'P',stateLine:'sold'},new Map()).status,'Đã bán');
  const projects=buildProjectInventory([{source:'vhub',project_id:1,project_name:'A'},{source:'vhub',project_id:2,project_name:'B'}],[{source:'vhub',project_id:1,project_name:'Alias'},{source:'vhub',project_id:3,project_name:'C'}]);
  assert.equal(projects.length,3);assert.equal(projects.reduce((s,p)=>s+p.count,0),2);
  assert.equal(projects.find(p=>p.project_name==='B').count,0);
  assert.equal(buildProjectInventory([], [{source:'vhub',project_id:3,project_name:'C',listing_state:'missing'}])[0].count,0);
  const period=getWeeklyPeriod(new Date('2026-11-22T18:00:00Z'));
  assert.equal(period.periodEnd.toISOString(),'2026-11-22T17:00:00.000Z');
  assert.equal(period.periodStart.toISOString(),'2026-11-15T17:00:00.000Z');
  const buffer=await buildExcelReport([{source:'vhub',unit_code:'TEST',...high}]);
  const wb=new ExcelJS.Workbook();await wb.xlsx.load(buffer);
  const sheet=wb.worksheets[0],headers=sheet.getRow(1).values;
  assert.equal(sheet.columnCount,37);assert.equal(sheet.autoFilter,'A1:AK2');
  assert.equal(sheet.getCell(2,headers.indexOf('Mặt tiền (m)')).value,'');
  // Use an isolated collection and delete only that collection after the test.
  const conn=await mongoose.createConnection('mongodb://127.0.0.1:27017/real_estate_test_db',{serverSelectionTimeoutMS:5000}).asPromise();
  const schema=require('../src/models/Unit').schema.clone();
  const collection=`report_audit_${process.pid}_${Date.now()}`;
  const Model=conn.model('ReportAudit',schema,collection);
  try {
    const filter={source:'hisale',project_name:'TEST',unit_code:'U1'};
    const ops=(price,status)=>[{updateOne:{filter,update:{$set:{price,status,raw_data:{price_loan:price}},$setOnInsert:{is_notified:false}},upsert:true}}];
    await trackedBulkWrite(Model,ops(100,'Còn hàng'));
    await trackedBulkWrite(Model,ops(100,'Còn hàng'));
    await trackedBulkWrite(Model,ops(120,'Đã bán'));
    const doc=await Model.findOne(filter).lean();
    assert.equal(doc.change_history.length,2);
    assert.equal(doc.change_history[1].changes.price.before,100);
    assert.equal(doc.change_history[1].changes.price.after,120);
    const rows=movementRows([doc],new Date(0),new Date(Date.now()+1000));
    assert.deepEqual(summarize(rows),{newUnits:1,priceChanged:1,sold:1,statusChanged:1,removed:0,relisted:0,events:2});
    const start=new Date(doc.change_history[1].at);
    assert.equal(movementRows([doc],start,start).length,0);
    await markMissing(Model,{source:'hisale',project_name:'TEST'},new Date(0));
    assert.equal((await Model.findOne(filter)).change_history.length,2);
    await markMissing(Model,{source:'hisale',project_name:'TEST'},new Date(Date.now()+1000));
    assert.equal((await Model.findOne(filter)).listing_state,'missing');
    await trackedBulkWrite(Model,ops(120,'Đã bán'));
    const final=await Model.findOne(filter).lean();
    const summary=summarize(movementRows([final],new Date(0),new Date(Date.now()+2000)));
    assert.equal(summary.removed,1);assert.equal(summary.relisted,1);assert.equal(summary.priceChanged,1);
  } finally {await Model.collection.drop();await conn.close();}
  console.log('Report requirements: source semantics, full projects, workbook filters, timezone and persisted history passed.');
}
main().catch(error=>{console.error(error);process.exit(1);});
